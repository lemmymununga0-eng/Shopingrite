import { useEffect, useState } from "react";
import { Link } from "react-router-dom";
import { Activity } from "lucide-react";
import { PasswordInput, passwordOk } from "../components/forms";
import { ErrorNotice, Loading, PageHeader } from "../components/ui";
import { useAuth } from "../context/AuthContext";
import { api } from "../services/api";
import { METHOD_OPTIONS, PAGE_SIZES, getPrefs, setPrefs } from "../services/prefs";

const TABS = [["account", "Account Preferences"], ["notifications", "Notifications"], ["security", "Security"], ["app", "Application Preferences"], ["privacy", "Data and Privacy"]];

function Saved({ ok, blocked }) {
  if (blocked) return <div className="notice error" role="alert">Your browser blocked saving preferences.</div>;
  return ok ? <div className="notice success" role="status">Saved in this browser.</div> : null;
}

function SystemStatus() {
  const [health, setHealth] = useState(null);
  const [model, setModel] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(true);
  useEffect(() => {
    Promise.all([api.health(), api.modelInfo()]).then(([h, m]) => { setHealth(h); setModel(m); })
      .catch(e => setError(e.message)).finally(() => setLoading(false));
  }, []);
  const m = model?.metrics;
  const Row = ({ label, children }) => <div className="setting-row"><span><Activity size={16} aria-hidden="true"/> {label}</span><strong>{children}</strong></div>;
  if (loading) return <Loading/>;
  return <>
    <ErrorNotice error={error}/>
    <Row label="FastAPI backend">{health ? "Connected" : "Not connected"}</Row>
    <Row label="Database backend">{health?.db_backend ?? "—"}</Row>
    <Row label="Server authentication">{health ? (health.auth_configured ? "Configured" : "Not configured") : "—"}</Row>
    <Row label="Random Forest model">{model?.trained ? "Loaded" : "Unavailable"}</Row>
    {model?.trained ? <>
      <Row label="Model version">{model.version}</Row>
      <Row label="Training data">{model.data_source}{model.is_synthetic ? " (synthetic)" : ""}</Row>
      <Row label="Flag threshold">{model.threshold}</Row>
      {m && <>
        <Row label="Precision / Recall / F1">{m.precision.toFixed(3)} / {m.recall.toFixed(3)} / {m.f1.toFixed(3)}</Row>
        <Row label="PR-AUC / ROC-AUC">{m.pr_auc?.toFixed(3) ?? "n/a"} / {m.roc_auc?.toFixed(3) ?? "n/a"}</Row>
        <Row label="Held-out test rows">{m.test_rows} ({m.test_fraud_rows ?? m.support_fraud} fraud)</Row></>}
      {model.is_synthetic && <p className="notice info">These metrics come from a synthetic dataset whose labels were generated by a formula. They do not show real-world fraud-detection performance.</p>}
      <h3>Most important features overall</h3><p className="muted-text">{model.importance_note}</p>
      <ul>{model.global_feature_importance.map(f => <li key={f.feature}>{f.feature}: {f.importance}</li>)}</ul>
    </> : <p className="notice info">{model?.message || "No model loaded."} Train one with <code>python train_model.py --synthetic</code> in the backend folder, then restart the API.</p>}
  </>;
}

function Security() {
  const { updatePassword } = useAuth();
  const [pw, setPw] = useState(""); const [confirm, setConfirm] = useState("");
  const [errors, setErrors] = useState({}); const [error, setError] = useState(""); const [ok, setOk] = useState(false); const [busy, setBusy] = useState(false);
  async function submit(e) {
    e.preventDefault(); setError(""); setOk(false);
    const errs = {};
    if (!passwordOk(pw)) errs.pw = "Use at least 8 characters with a letter and a number";
    if (pw !== confirm) errs.confirm = "The passwords do not match";
    setErrors(errs);
    if (Object.keys(errs).length) return;
    setBusy(true);
    try { await updatePassword(pw); setOk(true); setPw(""); setConfirm(""); }
    catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }
  return <form onSubmit={submit} noValidate>
    <h3>Change password</h3><p className="muted-text">Handled by Supabase Auth. Your password is never stored by this application.</p>
    <PasswordInput label="New password" error={errors.pw} autoComplete="new-password" value={pw} onChange={e => setPw(e.target.value)}/>
    <PasswordInput label="Confirm new password" error={errors.confirm} autoComplete="new-password" value={confirm} onChange={e => setConfirm(e.target.value)}/>
    {ok && <div className="notice success" role="status">Password updated.</div>}
    {error && <div className="notice error" role="alert">{error}</div>}
    <button className="btn btn-primary" disabled={busy}>{busy ? "Updating…" : "Update password"}</button>
    <p className="muted-text">Forgot your password instead? <Link to="/forgot-password">Send a reset link</Link>. Use Logout (sidebar) to end this session.</p>
  </form>;
}

export default function Settings() {
  const { user, role } = useAuth();
  const [tab, setTab] = useState("account");
  const [prefs, setLocal] = useState(getPrefs);
  const [state, setState] = useState({ ok: false, blocked: false });
  function change(patch) {
    const stored = setPrefs(patch);
    setLocal(p => ({ ...p, ...patch })); setState({ ok: stored, blocked: !stored });
  }
  return <div>
    <PageHeader title="Settings" subtitle="Preferences, security and system status."/>
    <div className="tabs" role="tablist" aria-label="Settings sections">
      {TABS.map(([id, label]) => <button key={id} role="tab" id={`tab-${id}`} aria-selected={tab === id} aria-controls={`panel-${id}`} className="tab" onClick={() => { setTab(id); setState({ ok: false, blocked: false }); }}>{label}</button>)}
    </div>
    <section className="panel" role="tabpanel" id={`panel-${tab}`} aria-labelledby={`tab-${tab}`}>
      {tab === "account" && <>
        <h3>Account</h3>
        <dl className="detail-grid"><dt>Name</dt><dd>{user?.user_metadata?.full_name || "—"}</dd><dt>Email</dt><dd>{user?.email}</dd><dt>Role</dt><dd style={{ textTransform: "capitalize" }}>{role}</dd></dl>
        <Link className="btn btn-secondary" to="/profile">Edit profile</Link></>}
      {tab === "notifications" && <>
        <div className="switch-row"><label htmlFor="badge"><strong>Alert notifications in the top bar</strong><small>Shows a bell with the number of alerts awaiting review. Turn off to hide it (takes effect on next page load).</small></label>
          <input id="badge" type="checkbox" role="switch" checked={prefs.alertBadge} onChange={e => change({ alertBadge: e.target.checked })}/></div>
        <Saved {...state}/></>}
      {tab === "security" && <Security/>}
      {tab === "app" && <>
        <div className="field"><label htmlFor="dm"><span>Default payment method</span></label>
          <select id="dm" value={prefs.defaultMethod} onChange={e => change({ defaultMethod: e.target.value })}>{METHOD_OPTIONS.map(m => <option key={m}>{m}</option>)}</select></div>
        <div className="field"><label htmlFor="ps"><span>Rows per page in History and Alerts</span></label>
          <select id="ps" value={prefs.pageSize} onChange={e => change({ pageSize: Number(e.target.value) })}>{PAGE_SIZES.map(n => <option key={n} value={n}>{n}</option>)}</select></div>
        <Saved {...state}/></>}
      {tab === "privacy" && <>
        <h3>What is stored</h3>
        <ul><li>Your account (name, email, role) in Supabase Auth. Passwords are handled by Supabase and never by this app.</li>
          <li>Each analysed transaction: reference, amount, payment method, hour, failed attempts, device/international flags, branch, the model's probability, risk level and your review notes.</li>
          <li>Preferences on this page, in this browser only.</li></ul>
        <h3>What is never collected</h3><p className="muted-text">Card numbers, CVVs, PINs or passwords. Customers can only see their own transactions; analysts and admins can see all in order to review alerts.</p>
        <h3>System status</h3><SystemStatus/></>}
    </section>
  </div>;
}
