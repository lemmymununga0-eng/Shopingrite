def test_stratified_split_is_80_20_keeps_class_ratio_and_never_overlaps():
    y = pd.Series([0] * 970 + [1] * 30)
    s = stratified_split(y)
    assert len(s.train_idx) == 800 and len(s.test_idx) == 200
    assert int(y.iloc[s.test_idx].sum()) == 6 and int(y.iloc[s.train_idx].sum()) == 24      # 3% in both partitions
    assert_no_overlap(s)
    assert sorted(np.concatenate([s.train_idx, s.test_idx]).tolist()) == list(range(1000))   # every row used exactly once


def test_group_split_keeps_every_group_on_one_side():
    rng = np.random.default_rng(1)
    groups = rng.integers(0, 200, 2000)
    y = pd.Series((rng.random(2000) < 0.3).astype(int))
    s = group_split(y, groups)
    assert not set(groups[s.train_idx]) & set(groups[s.test_idx])
    assert 0.1 < len(s.test_idx) / 2000 < 0.35 and "group" in s.method
    assert_no_overlap(s, groups)


def test_chronological_split_puts_the_newest_rows_in_the_test_set():
    order = np.random.default_rng(2).permutation(1000)
    s = chronological_split(order)
    assert order[s.train_idx].max() < order[s.test_idx].min() and len(s.test_idx) == 200


