# ------------------------------------------------------------------------------------------------------------ fixtures
def make_cc_fixture(n=4000, fraud=160, seed=7, signal=2.5) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    y = np.zeros(n, dtype=int)
    y[rng.choice(n, fraud, replace=False)] = 1
    data = {"Time": np.sort(rng.uniform(0, 172800, n))}
    for i in range(1, 29):
        data[f"V{i}"] = rng.normal(0, 1, n) + (signal * y * (1 if i % 3 == 0 else 0) * (1 if i <= 9 else 0))
    data["Amount"] = np.round(rng.lognormal(3.0, 1.0, n), 2)
    data["Class"] = y.astype(str)                                    # OpenML ships the label as text: the adapter must cope
    return pd.DataFrame(data)


def make_paysim_fixture(n=6000, seed=11) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    types = rng.choice(["PAYMENT", "CASH_IN", "CASH_OUT", "TRANSFER", "DEBIT"], n, p=[0.35, 0.22, 0.28, 0.1, 0.05])
    old = np.round(rng.lognormal(8, 1.5, n), 2)
    amount = np.round(old * rng.uniform(0.01, 0.9, n), 2)
    fraud = np.zeros(n, dtype=int)
    risky = np.where(np.isin(types, ["TRANSFER", "CASH_OUT"]))[0]
    pick = rng.choice(risky, 150, replace=False)
    fraud[pick] = 1
    amount[pick] = old[pick]                                          # the simulator's pattern: drain the account
    new_orig = np.where(fraud == 1, 0.0, np.maximum(old - amount, 0))     # post-event balance leaks the label (must be excluded)
    return pd.DataFrame({"step": rng.integers(1, 744, n), "type": types, "amount": amount, "nameOrig": [f"C{i}" for i in range(n)],
                         "oldbalanceOrg": old, "newbalanceOrig": new_orig,
                         "nameDest": [("M" if t == "PAYMENT" else "C") + str(rng.integers(1e6)) for t in types],
                         "oldbalanceDest": np.round(rng.lognormal(7, 1.5, n), 2), "newbalanceDest": 0.0, "isFraud": fraud, "isFlaggedFraud": 0})


def make_phish_fixture(n=3000, seed=3) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = []
    for i in range(n):
        phish = rng.random() < 0.45
        host = f"site{i % 800}.com" if not phish else f"secure-login-{rng.integers(99999)}.{rng.choice(['xyz', 'top', 'info'])}"
        url = f"https://www.{host}" if not phish else f"http://{host}/verify/account?id={rng.integers(1e6)}&token={rng.integers(1e9)}"
        rows.append({"URL": url, "Domain": host, "label": 0 if phish else 1})
    return pd.DataFrame(rows)


